/// Create a default phase definition
fn default_phase(name: String) -> PhaseDefinition {
    PhaseDefinition {
        id: String::new(), // Generated by backend
        name,
        enabled: true,
        display_text: None,
        start_trigger: Trigger::CombatStart,
        end_trigger: None,
        preceded_by: None,
        conditions: vec![],
        counter_condition: None,
        resets_counters: vec![],
        difficulties: vec![],
    }
}

#[component]
pub fn PhasesTab(
    boss_with_path: BossWithPath,
    encounter_data: EncounterData,
    expanded_phase: Signal<Option<String>>,
    hide_disabled_phases: Signal<bool>,
    on_change: EventHandler<Vec<PhaseDefinition>>,
    on_refetch: EventHandler<()>,
    on_status: EventHandler<(String, bool)>,
) -> Element {
    let guard = use_drawer_guard();
    // Extract phases and badge IDs from BossWithPath
    let phases = boss_with_path.boss.phases.clone();
    // A–Z when toggled; renaming leaves the row in place
    let rank = use_stable_rank(phases.iter().map(|x| (x.id.as_str(), x.name.as_str())), ENCOUNTER_SORT_AZ());
    let builtin_phase_ids = boss_with_path.builtin_phase_ids.clone();
    let modified_phase_ids = boss_with_path.modified_phase_ids.clone();

    let disabled_count = phases.iter().filter(|p| !p.enabled).count();

    // Filter phases based on toggle
    let mut visible_phases: Vec<PhaseDefinition> = if hide_disabled_phases() {
        phases.iter().filter(|p| p.enabled).cloned().collect()
    } else {
        phases.clone()
    };
    apply_rank(&mut visible_phases, &rank.read(), |x| &x.id);
    let origin_of = |id: &str| Origin::of(builtin_phase_ids.iter().any(|b| b == id), modified_phase_ids.iter().any(|m| m == id));
    let origin_counts = origin_counts(phases.iter().map(|x| origin_of(&x.id)));
    let origin_filter = ENCOUNTER_ORIGIN();
    visible_phases.retain(|x| origin_filter.is_none_or(|o| origin_of(&x.id) == o));

    rsx! {
        div { class: "phases-tab",
            // Header
            div { class: "flex items-center justify-between mb-sm editor-tab-header",
                div { class: "flex items-center gap-sm",
                    span { class: "text-sm text-secondary", "{phases.len()} phases" }
                    if disabled_count > 0 {
                        label { class: "flex items-center gap-xs text-xs text-muted cursor-pointer",
                            input {
                                r#type: "checkbox",
                                checked: hide_disabled_phases(),
                                onchange: move |e| hide_disabled_phases.set(e.checked()),
                            }
                            "Hide disabled ({disabled_count})"
                        }
                    }
                    SortToggle { az: ENCOUNTER_SORT_AZ.signal() }
                    OriginFilter { selected: origin_filter, counts: origin_counts, kind: "phases", on_pick: move |o| *ENCOUNTER_ORIGIN.write() = o }
                }
                {
                    let bwp = boss_with_path.clone();
                    let phases_for_create = phases.clone();
                    rsx! {
                        InlineNameCreator {
                            button_label: "+ New Phase",
                            placeholder: "Phase name...",
                            on_create: move |name: String| {
                                let phases_clone = phases_for_create.clone();
                                let boss_id = bwp.boss.id.clone();
                                let file_path = bwp.file_path.clone();
                                let phase = default_phase(name);
                                let item = EncounterItem::Phase(phase);
                                spawn(async move {
                                    match api::create_encounter_item(&boss_id, &file_path, &item).await {
                                        Ok(EncounterItem::Phase(created)) => {
                                            let created_id = created.id.clone();
                                            let mut current = phases_clone;
                                            current.push(created);
                                            on_change.call(current);
                                            expanded_phase.set(Some(created_id));
                                            on_status.call(("Created".to_string(), false));
                                        }
                                        Ok(_) => on_status.call(("Unexpected response type".to_string(), true)),
                                        Err(e) => on_status.call((e, true)),
                                    }
                                });
                            }
                        }
                    }
                }
            }

            // Phase list
            if visible_phases.is_empty() {
                if phases.is_empty() {
                    div { class: "empty-state text-sm", "No phases defined" }
                } else {
                    div { class: "empty-state text-sm", "No phases match the filters" }
                }
            } else {
                for phase in visible_phases {
                    {
                        let phase_key = phase.id.clone();
                        let is_expanded = expanded_phase() == Some(phase_key.clone());
                        let phases_for_row = phases.clone();
                        let phase_is_builtin = builtin_phase_ids.contains(&phase.id);
                        let phase_is_modified = modified_phase_ids.contains(&phase.id);

                        rsx! {
                            PhaseRow {
                                key: "{phase_key}",
                                phase: phase.clone(),
                                all_phases: phases_for_row,
                                is_builtin: phase_is_builtin,
                                is_modified: phase_is_modified,
                                boss_with_path: boss_with_path.clone(),
                                expanded: is_expanded,
                                encounter_data: encounter_data.clone(),
                                on_toggle: move |_| {
                                    guard.switch(expanded_phase, if is_expanded { None } else { Some(phase_key.clone()) });
                                },
                                on_change: on_change,
                                on_refetch: on_refetch,
                                on_status: on_status,
                                on_collapse: move |_| expanded_phase.set(None),
                            }
                        }
                    }
                }
            }
        }
    }
}

